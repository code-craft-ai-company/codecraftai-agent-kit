"""
    Provides the :func:`create_tool` factory function for creating Tool instances
    without requiring subclassing.

    The factory function creates a dynamic Tool subclass internally that delegates
    the execute method to a provided callable, allowing quick tool creation with
    minimal boilerplate.
"""

from ccai.agentkit.tool import Tool


def create_tool(name: str, description: str, input_schema: dict,
                output_schema: dict, execute_fn: callable,
                version: str = "1.0.0", tags: dict = None) -> Tool:
    """
        Factory function that creates a Tool instance without requiring subclassing.

        Internally creates a dynamic Tool subclass with the provided metadata and
        an execute method that delegates to the provided callable.

        :param name: Tool name.
        :param description: Tool description.
        :param input_schema: Input schema as a dictionary.
        :param output_schema: Output schema as a dictionary.
        :param execute_fn: Callable implementing the tool logic. Must accept
            (inputs, credentials) and return a dictionary.
        :param version: Tool version string.
        :param tags: Optional tags dictionary.

        :returns: A Tool instance with the specified configuration.
    """

    bound_execute_fn = execute_fn

    class DynamicTool(Tool):
        """
            A dynamically created Tool subclass generated by the create_tool factory.
        """

        TOOL_NAME = name
        TOOL_DESCRIPTION = description
        TOOL_VERSION = version
        INPUT_SCHEMA = input_schema
        OUTPUT_SCHEMA = output_schema

        def execute(self, inputs: dict, credentials: dict = None) -> dict:
            """
                Delegates execution to the callable provided to create_tool.

                :param inputs: Validated input dictionary.
                :param credentials: Optional dictionary of resolved credentials.

                :returns: Output dictionary from the delegate callable.
            """
            rtnval = bound_execute_fn(inputs, credentials)
            return rtnval

    rtnval = DynamicTool(tags=tags)
    return rtnval
